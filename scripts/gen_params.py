# gen_params.py : writes rtl/produce_params.vh from scripts/config.py
import config as c
names = dict(W=c.W, H=c.H, HB=c.HB, VB=c.VB, OB=c.OB, N=c.N, RECIP=c.RECIP, SHIFT=c.SHIFT, MIN_LEVEL=c.MIN_LEVEL,
             CNT_W=c.CNT_W, OC_MODE=c.OC_MODE, CENTER=c.CENTER, CPB=c.CPB_HW,
             CPB_SIM=c.CPB_SIM, SKIP=c.SKIP_FRAMES)
with open("rtl/produce_params.vh", "w") as f:
    f.write("// GENERATED by scripts/gen_params.py from scripts/config.py - do not edit\n")
    f.write("`ifndef PRODUCE_PARAMS_VH\n`define PRODUCE_PARAMS_VH\n")
    for k, v in names.items():
        f.write(f"`define CFG_{k} {v}\n")
    f.write("`endif\n")
print("wrote rtl/produce_params.vh :", names)
